package com.example.demo.restaurant.response;

public class ResponseRestaurant {
    private String id;
    private String name;

    public ResponseRestaurant(String id, String name) {
        this.id = id;
        this.name = name;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
